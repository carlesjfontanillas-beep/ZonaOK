const assert=require('node:assert/strict');
const {totals,category}=require('../zonaok-player-totals.js');
const m=(leagueId,teamFilterId,groupName,sports)=>({leagueId,teamFilterId,groupName,sports,seasonId:'41'});
const inf=m('4786','10','INFANTIL OR 10',{played:8,goals:10,assists:0,blueCards:1,redCards:0});
const ju6=m('4784','6','JUVENIL OR 6',{played:4,goals:2,assists:0,blueCards:0,redCards:0});
const ju8=m('4790','8','JUVENIL OR 8',{played:4,goals:2,assists:0,blueCards:0,redCards:0});
const rows=[inf,ju6,ju8];
const act=(m,i,goals,blueCards)=>({leagueId:m.leagueId,teamFilterId:m.teamFilterId,seasonId:'41',matchId:String(i),participation:'listed',stats:{...(goals===undefined?{}:{goals}),...(blueCards===undefined?{}:{blueCards})}});
const acts=[...[1,2,1,undefined,1,undefined,2,3].map((g,i)=>act(inf,i+1,g,i===3?1:undefined)),act(ju6,11),act(ju6,12),act(ju6,13,2),act(ju8,14)];
const get=ms=>totals(ms,rows,acts).sp;
assert.equal(category(ju6).key,category(ju8).key);
assert.notEqual(category(ju6).key,category(inf).key);
assert.deepEqual([get(rows).played,get(rows).goals],[12,12]);
assert.deepEqual([get([ju6,ju8]).played,get([ju6,ju8]).goals],[4,2]);
assert.deepEqual([get([ju6]).played,get([ju6]).goals],[3,2]);
assert.deepEqual([get([ju8]).played,get([ju8]).goals],[1,0]);
assert.equal(get(rows).blueCards,1);
assert.equal(get([ju8]).redCards,0);
assert.equal(get([ju8]).assists,0);
const partial=totals([ju8],rows,acts.slice(0,-1));assert.equal(partial.sp.played,undefined);assert.ok(partial.partial.includes('played'));
const conflict=totals([ju6,ju8],[ju6,{...ju8,sports:{played:3,goals:5}}],acts);assert.notEqual(conflict.sp.goals,7);
assert.equal(totals(rows,rows,[...acts,acts[0]]).sp.played,12);
const sameLeague={...ju8,leagueId:ju6.leagueId};
const uncertain={...act(ju6,99,2),teamFilterId:undefined};
assert.equal(totals([ju6],[ju6,sameLeague],[uncertain]).sp.goals,undefined);
const additional=[...acts,act(ju8,15,2),act(ju8,16,2),act(ju8,17,2),act(ju8,18,2)];
assert.notEqual(totals([ju6,ju8],rows,additional).sp.goals,2);
